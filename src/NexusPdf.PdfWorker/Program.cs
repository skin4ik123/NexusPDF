// PdfWorker — каркас изолированного процесса PDF-операций (этап 3 плана).
//
// Назначение: рендеринг/OCR/сжатие недоверенных документов в отдельном
// процессе, чтобы сбой нативной библиотеки не закрывал интерфейс, а память и
// время операций можно было жёстко ограничивать. Связь — именованные каналы,
// крупные результаты — memory-mapped files.
//
// Сейчас основное приложение выполняет PDFium-операции в собственном выделенном
// потоке (см. NexusPdf.Pdf.Pdfium.PdfiumThread); перенос в этот процесс
// запланирован и честно отражён в docs/KNOWN_LIMITATIONS.md.

if (args.Length > 0 && args[0] == "--version")
{
    Console.WriteLine("NexusPdf.PdfWorker 0.1.0 (каркас, IPC ещё не реализован)");
    return 0;
}

Console.Error.WriteLine("PdfWorker запускается только основным приложением NexusPDF.");
return 2;
