namespace NexusPdf.Application;

/// <summary>
/// Растровый шрифт 5×7 для подписей на печатном листе: номер листа, метка
/// плитки плаката, печатное наложение.
///
/// Почему не настоящий шрифт: строка в углу листа рисуется поверх готового
/// растра, а тянуть сюда типографику WPF означало бы зависимость рендера
/// печати от потока интерфейса. Набор символов ограничен латиницей,
/// кириллицей и цифрами — этого хватает подписям; неизвестный символ
/// заменяется точкой, а не пропускается молча.
/// </summary>
internal static class TinyFont
{
    private const int GlyphWidth = 5;
    private const int GlyphHeight = 7;

    /// <summary>Каждая строка глифа — 5 бит, старший бит слева.</summary>
    private static readonly Dictionary<char, byte[]> Glyphs = Build();

    public static void Draw(
        byte[] buffer, int stride, int width, int height,
        string text, int x, int y, int pixelSize)
    {
        var size = Math.Max(1, pixelSize);
        var cursor = x;

        foreach (var raw in text)
        {
            var ch = char.ToUpperInvariant(raw);
            if (ch == ' ')
            {
                cursor += (GlyphWidth + 1) * size;
                continue;
            }

            var glyph = Glyphs.TryGetValue(ch, out var found) ? found : Glyphs['.'];
            for (var row = 0; row < GlyphHeight; row++)
            {
                var bits = glyph[row];
                for (var col = 0; col < GlyphWidth; col++)
                {
                    if ((bits & (1 << (GlyphWidth - 1 - col))) == 0) continue;
                    FillBlock(buffer, stride, width, height,
                        cursor + col * size, y + row * size, size);
                }
            }
            cursor += (GlyphWidth + 1) * size;
            if (cursor >= width) return; // строка не влезла — обрываем, не заворачивая
        }
    }

    private static void FillBlock(byte[] buffer, int stride, int width, int height, int x, int y, int size)
    {
        for (var dy = 0; dy < size; dy++)
        for (var dx = 0; dx < size; dx++)
        {
            var px = x + dx;
            var py = y + dy;
            if (px < 0 || py < 0 || px >= width || py >= height) continue;
            var offset = py * stride + px * 4;
            buffer[offset] = 0x40;
            buffer[offset + 1] = 0x40;
            buffer[offset + 2] = 0x40;
        }
    }

